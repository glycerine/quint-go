func IsBuiltinOpcode(opcode string) bool {
	switch opcode {
	case "List", "Map", "Rec", "Set", "Tup", "actionAll", "actionAny", "allLists", "allListsUpTo", "always", "and", "append", "assert", "expect", "assign", "chooseSome", "concat", "contains", "enabled", "eq", "eventually", "exclude", "exists", "fail", "field", "fieldNames", "filter", "flatten", "fold", "foldl", "foldr", "forall", "apalache::generate", "get", "head", "iadd", "idiv", "iff", "igt", "igte", "ilt", "ilte", "imod", "implies", "imul", "in", "indices", "intersect", "ipow", "isFinite", "isub", "ite", "item", "iuminus", "keys", "leadsTo", "length", "map", "mapBy", "matchVariant", "mustChange", "neq", "next", "not", "nth", "oneOf", "or", "orKeep", "powerset", "put", "q::test", "q::testOnce", "q::debug", "range", "replaceAt", "reps", "select", "set", "setBy", "setOfMaps", "setToMap", "size", "slice", "strongFair", "subseteq", "tail", "then", "to", "tuples", "union", "variant", "weakFair", "with":
		return true
	}
	return false
}
func IsBuiltinApp(e Expr) bool { return e.Kind == "app" && IsBuiltinOpcode(e.Opcode) }
