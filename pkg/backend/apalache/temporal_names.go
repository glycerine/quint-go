package apalache

import (
	"fmt"
	"strconv"
	"strings"

	quint "github.com/glycerine/quint-go/pkg"
)

// validateTemporalNames prevents legal user declarations from sharing state
// with the Go checker's temporal encoding. In particular, a user __InLoop can
// prevent a valid lasso from being selected and turn a violation into success.
// This is a preparation restriction until the checker generates hygienic names.
func validateTemporalNames(compiled quint.CompilationResult, options CheckOptions) *PreparationError {
	if len(options.Temporal) == 0 {
		return nil
	}
	// Saved variables use the entire imported/flattened name. For example,
	// I::__InLoop is distinct from the checker's fixed __InLoop variable.
	generated := map[string]bool{"__InLoop": true, "__LoopOK": true}
	for _, declaration := range compiled.MainModule.Declarations {
		if declaration.Kind == "var" {
			generated["__saved_"+declaration.Name] = true
		}
	}
	for _, property := range options.Temporal {
		generated["__"+property+"_init"] = true
	}
	diagnostics := []quint.Diagnostic{}
	for _, declaration := range compiled.MainModule.Declarations {
		// The Quint importer omits aliases and run definitions; these names
		// never enter the checker's shared declaration namespace.
		if declaration.Kind != "var" && declaration.Kind != "const" && declaration.Kind != "def" && declaration.Kind != "assume" || declaration.Kind == "def" && declaration.Qualifier == quint.Run {
			continue
		}
		if !generated[declaration.Name] && !temporalGeneratedTableauName(declaration.Name) {
			continue
		}
		id := declaration.ID
		diagnostics = append(diagnostics, quint.Diagnostic{
			Code:      quint.QNT000,
			Message:   fmt.Sprintf("Declaration %q conflicts with state generated by Go Apalache for temporal verification. Rename the declaration.", declaration.Name),
			Reference: &id,
		})
	}
	if len(diagnostics) == 0 {
		return nil
	}
	return &PreparationError{Explanation: "Cannot prepare temporal verification", Diagnostics: diagnostics}
}

// The shared UniqueNameGenerator produces t_<positive canonical base-36 uint64>.
// Earlier desugaring can consume an unknown number of names before the temporal
// pass, so reserve this exact generated family instead of a broad __ prefix.
// Tableau nodes, their saved copies, and eventual/always auxiliaries use it.
func temporalGeneratedTableauName(name string) bool {
	saved := strings.HasPrefix(name, "__saved_")
	if saved {
		name = strings.TrimPrefix(name, "__saved_")
	}
	if !strings.HasPrefix(name, "__temporal_t_") {
		return false
	}
	token := strings.TrimPrefix(name, "__temporal_t_")
	if !saved {
		if strings.HasSuffix(token, "_unroll_prev") {
			token = strings.TrimSuffix(token, "_unroll_prev")
		} else {
			token = strings.TrimSuffix(token, "_unroll")
		}
	}
	number, err := strconv.ParseUint(token, 36, 64)
	return err == nil && number > 0 && strconv.FormatUint(number, 36) == token
}

// validateTemporalQuantifiers rejects quantifiers over temporal formulas before
// the checker sees them. Otherwise Go Apalache reports an internal rewrite error
// (variable is not assigned a value) that does not name the unsupported form.
// The CLI requests an aggregate property (q::temporalProps), so every definition
// reachable from the requested names is scanned.
func validateTemporalQuantifiers(compiled quint.CompilationResult, options CheckOptions) *PreparationError {
	if len(options.Temporal) == 0 {
		return nil
	}
	definitions := map[string]*quint.Declaration{}
	for i := range compiled.MainModule.Declarations {
		declaration := &compiled.MainModule.Declarations[i]
		if declaration.Kind == "def" && declaration.Expr != nil {
			definitions[declaration.Name] = declaration
		}
	}
	reached := map[string]bool{}
	queue := append([]string{}, options.Temporal...)
	for len(queue) > 0 {
		name := queue[0]
		queue = queue[1:]
		if reached[name] || definitions[name] == nil {
			continue
		}
		reached[name] = true
		queue = append(queue, referencedNames(definitions[name].Expr)...)
	}
	diagnostics := []quint.Diagnostic{}
	for _, declaration := range compiled.MainModule.Declarations {
		if declaration.Kind != "def" || !reached[declaration.Name] || declaration.Expr == nil {
			continue
		}
		if quantifier := temporalQuantifierIn(declaration.Expr); quantifier != nil {
			id := quantifier.ID
			diagnostics = append(diagnostics, quint.Diagnostic{
				Code: quint.QNT000,
				Message: fmt.Sprintf("Temporal property %q quantifies over a temporal formula with %q. "+
					"Go Apalache does not support quantified temporal properties; state each instance as a separate temporal property.",
					declaration.Name, quantifier.Opcode),
				Reference: &id,
			})
		}
		if nested := nestedLeadsToIn(declaration.Expr); nested != nil {
			id := nested.ID
			diagnostics = append(diagnostics, quint.Diagnostic{
				Code: quint.QNT000,
				Message: fmt.Sprintf("Temporal property %q nests a leadsTo inside another leadsTo. "+
					"Apalache rejects this shape; rewrite it with a conjunction or a separate temporal property.",
					declaration.Name),
				Reference: &id,
			})
		}
	}
	if len(diagnostics) == 0 {
		return nil
	}
	return &PreparationError{Explanation: "Unsupported temporal property", Diagnostics: diagnostics}
}

// referencedNames collects every name and opcode in an expression tree. A
// definition reference may appear as either, so both are over-approximated.
func referencedNames(expression *quint.Expr) []string {
	if expression == nil {
		return nil
	}
	names := []string{expression.Name, expression.Opcode}
	for i := range expression.Args {
		names = append(names, referencedNames(&expression.Args[i])...)
	}
	return append(names, referencedNames(expression.Body)...)
}

// temporalQuantifierIn returns the first forall/exists whose body contains a
// temporal operator, or nil. Lambda bodies are reached through Body and Args.
func temporalQuantifierIn(expression *quint.Expr) *quint.Expr {
	if expression == nil {
		return nil
	}
	if (expression.Opcode == "forall" || expression.Opcode == "exists") && containsTemporalOperator(expression) {
		return expression
	}
	for i := range expression.Args {
		if found := temporalQuantifierIn(&expression.Args[i]); found != nil {
			return found
		}
	}
	return temporalQuantifierIn(expression.Body)
}

// nestedLeadsToIn returns the first leadsTo that has another leadsTo in either
// operand, or nil. Upstream Apalache rejects this shape ("Unexpected expressions"),
// and the Go checker would otherwise leak an internal desugarer error.
func nestedLeadsToIn(expression *quint.Expr) *quint.Expr {
	if expression == nil {
		return nil
	}
	if expression.Opcode == "leadsTo" {
		for i := range expression.Args {
			if containsOpcode(&expression.Args[i], "leadsTo") {
				return expression
			}
		}
	}
	for i := range expression.Args {
		if found := nestedLeadsToIn(&expression.Args[i]); found != nil {
			return found
		}
	}
	return nestedLeadsToIn(expression.Body)
}

func containsOpcode(expression *quint.Expr, opcode string) bool {
	if expression == nil {
		return false
	}
	if expression.Opcode == opcode {
		return true
	}
	for i := range expression.Args {
		if containsOpcode(&expression.Args[i], opcode) {
			return true
		}
	}
	return containsOpcode(expression.Body, opcode)
}

func containsTemporalOperator(expression *quint.Expr) bool {
	if expression == nil {
		return false
	}
	switch expression.Opcode {
	case "always", "eventually", "leadsTo", "weakFair", "strongFair":
		return true
	}
	for i := range expression.Args {
		if containsTemporalOperator(&expression.Args[i]) {
			return true
		}
	}
	return containsTemporalOperator(expression.Body)
}
