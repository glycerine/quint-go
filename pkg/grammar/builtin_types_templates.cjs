// Regenerate with: go generate ./pkg
// Both outputs use the reference parser, independently of the Go implementation.
const crypto = require('crypto')
const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '../..')
const source = fs.readFileSync(path.join(root, 'quint/src/types/builtinSignatures.ts'), 'utf8')
const entries = [...source.matchAll(/\{ name: '([^']+)', type: '([^']+)' \}/g)]
  .map(([, name, signature]) => ({ name, signature }))
  .sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
if (entries.length === 0 || new Set(entries.map(entry => entry.name)).size !== entries.length) {
  throw new Error('Expected unique fixed builtin signature definitions')
}
require(path.join(root, 'quint/node_modules/ts-node')).register({
  project: path.join(root, 'quint/tsconfig.json'),
  transpileOnly: true,
})
const { getSignatures } = require(path.join(root, 'quint/src/types/builtinSignatures'))
const signatures = getSignatures()
const cases = entries.map(({ name, signature }) => {
  const parse = signatures.get(name)
  if (!parse) throw new Error(`Missing reference signature: ${name}`)
  const parsed = parse(0)
  const scheme = JSON.parse(JSON.stringify({
    type: parsed.type,
    typeVariables: [...parsed.typeVariables],
    rowVariables: [...parsed.rowVariables],
  }, (key, value) => key === 'id' ? undefined : value))
  return { name, signature, scheme }
})
const hash = crypto.createHash('sha256')
for (const { name, signature } of entries) hash.update(`${name}\0${signature}\n`)
const digest = hash.digest('hex')
const quote = JSON.stringify
const stringSlice = strings => `[]string{${strings.map(quote).join(',')}}`

function checkFields(value, allowed) {
  for (const name of Object.keys(value)) {
    if (!allowed.includes(name)) throw new Error(`Unsupported field ${name} in ${JSON.stringify(value)}`)
  }
}

function typeLiteral(type) {
  checkFields(type, ['kind', 'name', 'elem', 'arg', 'res', 'args', 'fields', 'ctor'])
  const fields = [`Kind:${quote(type.kind)}`]
  if (type.name !== undefined) fields.push(`Name:${quote(type.name)}`)
  for (const [js, go] of [['elem', 'Elem'], ['arg', 'Arg'], ['res', 'Res'], ['ctor', 'Ctor']]) {
    if (type[js] !== undefined) fields.push(`${go}:&${typeLiteral(type[js])}`)
  }
  if (type.args !== undefined) fields.push(`Args:[]Type{${type.args.map(typeLiteral).join(',')}}`)
  if (type.fields !== undefined) fields.push(`Fields:&${rowLiteral(type.fields)}`)
  return `Type{${fields.join(',')}}`
}

function rowLiteral(row) {
  checkFields(row, ['kind', 'name', 'fields', 'other'])
  const fields = [`Kind:${quote(row.kind)}`]
  if (row.name !== undefined) fields.push(`Name:${quote(row.name)}`)
  if (row.fields !== undefined) fields.push(`Fields:[]RowField{${row.fields.map(field => {
    checkFields(field, ['fieldName', 'fieldType'])
    return `{Name:${quote(field.fieldName)},Type:${typeLiteral(field.fieldType)}}`
  }).join(',')}}`)
  if (row.other !== undefined) fields.push(`Other:&${rowLiteral(row.other)}`)
  return `Row{${fields.join(',')}}`
}

const generated = path.join(root, 'pkg/builtin_types_templates_generated.go')
const lines = [
  '// Code generated by node grammar/builtin_types_templates.cjs; DO NOT EDIT.',
  '',
  'package quint',
  '',
  '// The digest includes each fixed name and its source signature, sorted by name.',
  `const fixedBuiltinTypeSourceSHA256 = ${quote(digest)}`,
  '',
  '// These parser-derived templates are private and immutable. Callers receive deep copies.',
  'var fixedBuiltinTypeCache = map[string]TypeScheme{',
  ...cases.map(({ name, scheme }) => `${quote(name)}:{Type:${typeLiteral(scheme.type)},TypeVariables:${stringSlice(scheme.typeVariables)},RowVariables:${stringSlice(scheme.rowVariables)}},`),
  '}',
  '',
]
fs.writeFileSync(generated, lines.join('\n'))
fs.writeFileSync(path.join(root, 'pkg/testdata/parser/builtin_types_fixed.json'), JSON.stringify(cases, null, 2) + '\n')
console.log(`Generated ${cases.length} fixed builtin type templates (${digest})`)
